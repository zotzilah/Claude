// Turns docs/legal/privacy-policy.md and terms.md into site/privacy.html and
// site/terms.html, styled like the landing page. Run after editing either file:
//   node site/build-legal.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const pages = [
  { md: 'docs/legal/privacy-policy.md', out: 'site/privacy.html', title: 'Privacy policy' },
  { md: 'docs/legal/terms.md', out: 'site/terms.html', title: 'Terms of use' },
];

const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';

for (const page of pages) {
  const source = readFileSync(new URL(page.md, root), 'utf8')
    // Links between the two documents point at the published pages.
    .replace(/\(privacy-policy\.md\)/g, '(privacy.html)')
    .replace(/\(terms\.md\)/g, '(terms.html)');
  const body = execFileSync(npx, ['--yes', 'marked@14.1.4', '--gfm'], { input: source, encoding: 'utf8', shell: process.platform === 'win32' });
  writeFileSync(new URL(page.out, root), template(page.title, body));
  console.log(`wrote ${page.out}`);
}

